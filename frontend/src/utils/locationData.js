export const countryItems = () => {
  const us = COUNTRIES.find((country) => country.code === US_COUNTRY_CODE);
  const rest = COUNTRIES.filter((country) => country.code !== US_COUNTRY_CODE);
  return [us, ...rest].map((country) => ({ title: country.name, value: country.code }));
};

export const usSubdivisionItems = () =>
  US_SUBDIVISIONS.map((subdivision) => ({ title: subdivision.name, value: subdivision.code }));

export const isUnitedStates = (country) => {
  if (!country) return false;
  const value = String(country).trim();
  if (value.toUpperCase() === US_COUNTRY_CODE) return true;
  return value.toLowerCase() === "united states";
};

export const countryName = (code) => {
  if (!code) return "";
  const match = COUNTRIES.find(
    (country) => country.code === code || country.name.toLowerCase() === String(code).trim().toLowerCase()
  );
  return match?.name || code;
};

export const subdivisionName = (code) => {
  if (!code) return "";
  const match = US_SUBDIVISIONS.find(
    (subdivision) =>
      subdivision.code === String(code).trim().toUpperCase() ||
      subdivision.name.toLowerCase() === String(code).trim().toLowerCase()
  );
  return match?.name || code;
};

export const resolveCountryCode = (value) => {
  if (!value) return "";
  const trimmed = String(value).trim();
  const byCode = COUNTRIES.find((country) => country.code === trimmed.toUpperCase());
  if (byCode) return byCode.code;
  const byName = COUNTRIES.find((country) => country.name.toLowerCase() === trimmed.toLowerCase());
  return byName?.code || trimmed;
};

export const resolveStateAbbrev = (value, country) => {
  if (!value) return "";
  const trimmed = String(value).trim();
  if (!isUnitedStates(country)) return trimmed;
  const upper = trimmed.toUpperCase();
  const byCode = US_SUBDIVISIONS.find((subdivision) => subdivision.code === upper);
  if (byCode) return byCode.code;
  const byName = US_SUBDIVISIONS.find(
    (subdivision) => subdivision.name.toLowerCase() === trimmed.toLowerCase()
  );
  return byName?.code || trimmed;
};

export const normalizeAddressFields = (address = {}) => {
  const country = resolveCountryCode(address.country);
  return {
    ...address,
    country,
    state_prov: resolveStateAbbrev(address.state_prov, country),
  };
};
